package mupdf

import (
	"path/filepath"
	"sync"
	"testing"
)

// Several goroutines, each with its own Context, render JPEG 2000 pages at
// the same time. MuPDF decodes JPX through OpenJPEG, whose allocator hooks are
// process-wide; MuPDF points them at the current context under one of its
// FZ_LOCK_* locks. Contexts created without locks raced on that pointer and
// freed memory with another context's allocator, crashing the process
// (MPDF-139). A crash takes the whole test binary down, so a failure here
// shows as a SIGSEGV rather than a failed assertion.
//
// The fixture is generated by testdata/make_jpx_pages.py.
func TestConcurrentJPXRendering(t *testing.T) {
	path := filepath.Join("testdata", "jpx_pages.pdf")
	const workers = 6
	const rounds = 3

	var wg sync.WaitGroup
	errs := make(chan error, workers*rounds*8)
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			ctx, err := NewContext()
			if err != nil {
				errs <- err
				return
			}
			defer ctx.Drop()
			doc, err := OpenDocument(ctx, path)
			if err != nil {
				errs <- err
				return
			}
			defer doc.Close()
			for r := 0; r < rounds; r++ {
				for p := 0; p < doc.CountPages(); p++ {
					img, err := doc.RenderPage(p, 150, nil)
					if err != nil {
						errs <- err
						return
					}
					if img.Bounds().Dx() != 1275 {
						t.Errorf("page %d rendered %d px wide, want 1275", p, img.Bounds().Dx())
					}
				}
			}
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
}
